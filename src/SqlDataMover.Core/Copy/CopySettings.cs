namespace SqlDataMover.Core.Copy;

public sealed class CopySettings
{
    /// <summary>Максимальный размер пакета строк (ограничивается 1500 параметрами SQL).</summary>
    public int BatchSize { get; init; } = 500;

    /// <summary>Продолжать копирование остальных таблиц при ошибке в одной таблице.</summary>
    public bool ContinueOnTableError { get; init; } = true;

    /// <summary>
    /// Разрешить временное задвоение значений уникальных полей: уникальные индексы приёмника
    /// (кроме первичного ключа) отключаются на время копирования каждой таблицы и пересоздаются
    /// перед коммитом. Нужно для таблиц с уникальными полями, когда в процессе копирования
    /// возникает транзиентный конфликт (например, новая строка со значением вставляется раньше,
    /// чем обновлением освободит его устаревшая строка). Требует права ALTER на таблицы приёмника.
    /// </summary>
    public bool AllowTemporaryUniqueDuplicates { get; init; }

    /// <summary>
    /// Режим предпросмотра: строки читаются и сопоставляются как при обычном копировании,
    /// но запись в приёмник не выполняется. Результат показывает, сколько строк в каждой
    /// таблице было бы вставлено и обновлено.
    /// </summary>
    public bool DryRun { get; init; }
}
